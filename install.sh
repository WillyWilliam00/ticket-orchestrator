#!/bin/sh
# Ticket Orchestrator installer. Safe to run again: it updates without touching your data.
set -eu

KIT="$(cd "$(dirname "$0")" && pwd)"
BIN_DIR="${TKO_BIN_DIR:-$HOME/.local/bin}"
CONFIG="${TKO_HOME:-$HOME/.config/ticket-orchestrator}"
BOT="${TKO_BOT:-ticket-orchestrator}"

say() { printf '%s\n' "$*"; }
fail() { printf 'install: %s\n' "$*" >&2; exit 1; }

# 1. A Node.js with built-in SQLite (22.13+). Automations run without your shell's PATH,
#    so the exact path is written into the wrapper.
has_sqlite() { "$1" -e "require('node:sqlite')" >/dev/null 2>&1; }
NODE=""
for candidate in "${TKO_NODE:-}" "$(command -v node 2>/dev/null || true)" \
  "$HOME"/.local/share/mise/installs/node/24/bin/node "$HOME"/.local/share/mise/installs/node/26/bin/node \
  /opt/homebrew/bin/node /usr/local/bin/node; do
  [ -n "$candidate" ] && [ -x "$candidate" ] && has_sqlite "$candidate" && { NODE="$candidate"; break; }
done
[ -n "$NODE" ] || fail "needs Node.js 22.13 or newer (node:sqlite). Set TKO_NODE=/path/to/node."
case "$NODE" in */mise/shims/*) NODE="$("$NODE" -e 'process.stdout.write(process.execPath)')";; esac

ORCA="${TKO_ORCA_BIN:-}"
[ -n "$ORCA" ] || { [ -x /Applications/Orca.app/Contents/Resources/bin/orca ] && ORCA=/Applications/Orca.app/Contents/Resources/bin/orca; }
[ -n "$ORCA" ] || ORCA="$(command -v orca 2>/dev/null || true)"
[ -n "$ORCA" ] || fail "Orca CLI not found. Install Orca, or set TKO_ORCA_BIN."
GH="$(command -v gh 2>/dev/null || true)"
[ -n "$GH" ] || fail "GitHub CLI (gh) not found."

# 2. The tko command: a wrapper with absolute paths.
mkdir -p "$BIN_DIR" "$CONFIG/profiles"
WRAPPER="$BIN_DIR/tko"
cat > "$WRAPPER" <<EOF
#!/bin/sh
# Generated by $KIT/install.sh — run it again to update.
# The caller's PATH is kept for project setup commands (they need the project's own Node).
export TKO_USER_PATH="\$PATH"
export PATH="$(dirname "$NODE"):$(dirname "$GH"):$(dirname "$ORCA"):/usr/bin:/bin:\$PATH"
export TKO_ORCA_BIN="$ORCA" TKO_GH_BIN="$GH" TKO_SELF="$WRAPPER" TKO_HOME="$CONFIG"
exec "$NODE" "$KIT/bin/tko.mjs" "\$@"
EOF
chmod +x "$WRAPPER"
say "✓ tko installed at $WRAPPER (node $("$NODE" -v))"
"$WRAPPER" where >/dev/null && say "✓ data folder $CONFIG"

# 3. The bot's soul and skills, if the bot already exists.
if [ -d "$HOME/.orca/bots/$BOT" ]; then
  "$WRAPPER" bot-sync --bot "$BOT" >/dev/null && say "✓ soul and skills copied into the bot \"$BOT\""
else
  say "• bot \"$BOT\" not found yet (step 2 below)"
fi

cat <<EOF

Next steps (details in README.md, "Setup, step by step"):
  2. In Orca, create a bot named exactly "$BOT", then run:  tko doctor --fix
  3. In the bot's chat, connect Google
  4. Copy profiles/example.json to $CONFIG/profiles/<project>.json and edit it
  5. tko seed           records the tickets you already have, so they are not proposed
  6. tko automations    creates the four automations, disabled
  7. Try one ticket ("take KEY" in the bot's chat), then enable the automations in Orca

At any point, tko doctor tells you what is missing.
EOF
